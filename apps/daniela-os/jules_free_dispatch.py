@dataclass
class JulesTask:
    """A task dispatched to Jules for autonomous coding."""

    id: str
    title: str
    description: str
    files_hint: list[str] = field(default_factory=list)
    test_required: bool = True
    priority: str = "normal"  # urgent, high, normal, low
    status: str = "queued"  # queued, dispatched, in_progress, pr_opened, merged, failed
    created_at: str = ""
    dispatched_at: str = ""
    pr_url: str = ""
    pr_number: int = 0
    jules_task_id: str = ""


class JulesDispatcher:
    """Manages the Jules free-tier task queue (15 tasks/day)."""

    DAILY_LIMIT = 15

    def __init__(self):
        self.state = self._load_state()

    def _load_state(self) -> dict:
        if STATE_FILE.exists():
            return json.loads(STATE_FILE.read_text(encoding="utf-8"))
        return {"tasks": [], "daily_count": {}, "last_reset": datetime.now().isoformat()}

    def _save_state(self):
        STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
        STATE_FILE.write_text(
            json.dumps(self.state, indent=2, ensure_ascii=False), encoding="utf-8"
        )

    def _today_key(self) -> str:
        return datetime.now().strftime("%Y-%m-%d")

    def _get_daily_count(self) -> int:
        today = self._today_key()
        return self.state["daily_count"].get(today, 0)

    def can_dispatch(self) -> bool:

        return self._get_daily_count() < self.DAILY_LIMIT

    def get_remaining_today(self) -> int:

        return self.DAILY_LIMIT - self._get_daily_count()

    def queue_task(
        self, title: str, description: str, files_hint: list[str] = None, priority: str = "normal"
    ) -> JulesTask:
        """Queue a task for Jules dispatch."""
        task = JulesTask(
            id=f"JULES-{len(self.state['tasks']) + 1:04d}",
            title=title,
            description=description,
            files_hint=files_hint or [],
            priority=priority,
            created_at=datetime.now().isoformat(),
        )
        self.state["tasks"].append(asdict(task))
        self._save_state()
        return task

    def dispatch_task(self, task_id: str) -> dict:
        """
        Dispatch a queued task to Jules.

        In production, this would call the Jules API:
        POST https://jules.google/api/v1/tasks
        {
            "repository": "github.com/user/aigestion",
            "prompt": task.description,
            "files": task.files_hint,
            "model": "gemini-2.5-flash"
        }

        For now, this prepares the dispatch payload and marks the task.
        """
        task = None
        for t in self.state["tasks"]:
            if t["id"] == task_id:
                task = t
                break

        if not task:
            return {"error": f"Task {task_id} not found"}

        if not self.can_dispatch():
            return {"error": f"Daily limit reached ({self.DAILY_LIMIT} tasks/day). Try tomorrow."}

        # Prepare Jules API payload (ready for integration)
        jules_payload = {
            "repository": JULES_CONFIG["repository"]["github_repo"],
            "branch": JULES_CONFIG["repository"]["default_branch"],
            "prompt": f"{task['title']}\n\n{task['description']}",
            "files_hint": task["files_hint"],
            "run_tests": task["test_required"],
            "model": JULES_CONFIG["free_tier"]["model"],
            "pr_template": JULES_CONFIG["repository"]["pr_template"],
        }

        # Mark as dispatched
        task["status"] = "dispatched"
        task["dispatched_at"] = datetime.now().isoformat()
        task["jules_payload"] = jules_payload

        # Increment daily count
        today = self._today_key()
        self.state["daily_count"][today] = self.state["daily_count"].get(today, 0) + 1

        self._save_state()

        return {
            "task_id": task_id,
            "status": "dispatched",
            "jules_payload": jules_payload,
            "remaining_today": self.get_remaining_today(),
            "note": "Payload ready. Connect Jules API to enable real dispatch.",
        }

    def mark_pr_opened(self, task_id: str, pr_url: str, pr_number: int):
        """Mark a task as having an open PR from Jules."""
        for t in self.state["tasks"]:
            if t["id"] == task_id:
                t["status"] = "pr_opened"
                t["pr_url"] = pr_url
                t["pr_number"] = pr_number
                self._save_state()
                return True
        return False

    def get_queue(self) -> list[dict]:
        """Get all tasks in the queue."""
        return self.state["tasks"]

    def get_status(self) -> dict:

        self._today_key()
        tasks = self.state["tasks"]
        by_status = {}
        for t in tasks:
            by_status.setdefault(t["status"], 0)
            by_status[t["status"]] += 1

        return {
            "free_tier": JULES_CONFIG["free_tier"],
            "daily_limit": self.DAILY_LIMIT,
            "used_today": self._get_daily_count(),
            "remaining_today": self.get_remaining_today(),
            "total_tasks": len(tasks),
            "by_status": by_status,
            "integrations": JULES_CONFIG["integrations"],
        }


