def print_status():
    dispatcher = JulesDispatcher()
    status = dispatcher.get_status()

    print("\n" + "=" * 60)

    print("  JULES FREE-TIER DISPATCH (GT-01)")
    print("=" * 60)

    print("\n  FREE TIER:")
    print(f"    Tasks/day: {status['free_tier']['tasks_per_day']}")
    print(f"    Concurrent: {status['free_tier']['concurrent_tasks']}")
    print(f"    Model: {status['free_tier']['model']}")
    print(f"    Cost: {status['free_tier']['cost']}")

    print("\n  TODAY:")
    print(f"    Used: {status['used_today']}/{status['daily_limit']}")
    print(f"    Remaining: {status['remaining_today']}")

    print("\n  QUEUE:")
    print(f"    Total tasks: {status['total_tasks']}")
    for status_name, count in status["by_status"].items():
        print(f"    {status_name}: {count}")

    print("\n  INTEGRATIONS:")
    for integ in status["integrations"]:
        print(f"    {integ['name']}: {integ['status']} — {integ['notes']}")

    print("\n  GITHUB WEBHOOK:")
    print(f"    Endpoint: {GITHUB_WEBHOOK_CONFIG['endpoint']}")
    print(f"    Events: {', '.join(GITHUB_WEBHOOK_CONFIG['events'])}")

    print("\n" + "=" * 60)


def main():
    if len(sys.argv) > 1:
        cmd = sys.argv[1]
        dispatcher = JulesDispatcher()

        if cmd == "status":
            print_status()

        elif cmd == "dispatch":
            if len(sys.argv) < 3:
                print('Usage: python jules_free_dispatch.py dispatch "task description"')
                return
            description = sys.argv[2]
            task = dispatcher.queue_task(
                title=description[:60],
                description=description,
                priority="normal",
            )
            result = dispatcher.dispatch_task(task.id)
            print(f"\nQueued task: {task.id}")
            print(f"Title: {task.title}")
            print(json.dumps(result, indent=2, ensure_ascii=False))

        elif cmd == "queue":
            tasks = dispatcher.get_queue()
            print(f"\nTask Queue ({len(tasks)} tasks):")
            for t in tasks:
                print(f"  [{t['id']}] {t['title']} — {t['status']}")

        elif cmd == "pr-config":
            print("\nGitHub PR Webhook Configuration:")
            print(json.dumps(GITHUB_WEBHOOK_CONFIG, indent=2, ensure_ascii=False))

        else:
            print(f"Unknown command: {cmd}")
            print("Usage: python jules_free_dispatch.py [status|dispatch|queue|pr-config]")
    else:
        print_status()


if __name__ == "__main__":
    main()
